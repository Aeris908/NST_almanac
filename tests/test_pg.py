"""Генератор Postgres: схема и запросы правки переводятся, и ни одна SQLite-овская фраза не остаётся.

Живого Postgres в этом окружении нет, поэтому проверяется то, что проверяемо без него: текст на
входе и текст на выходе. Главный смысл — охрана: если в путь правки внёсся приём, о котором
`db/pg.py` не знает, тест падает здесь, а не на боевой базе.
"""

import re

import pytest
from db import api, edit, pg, publish, store

CREATE_TABLE = re.compile(r"create table (?:if not exists )?(\w+)", re.IGNORECASE)


def _instructions(text):
    """Текст схемы без строк-комментариев: проверять надо инструкции, а не прозу вокруг них."""
    return "\n".join(line for line in text.splitlines() if not line.strip().startswith("--"))


def _table(text, name):
    """Тело таблицы из текста DDL — с описанием или без, регистр не важен."""
    found = re.search(rf"create table (?:if not exists )?{name} \((.*?)\n\);", text, re.I | re.S)
    assert found, f"в тексте нет таблицы {name}"
    return found.group(1)


def _columns(body):
    return [match.group(1) for match in re.finditer(r"^\s*(\w+)\s+\w", body, re.M)]


def _sqlite_tables():
    """Таблицы, которые создаёт файл схемы: и телом, и шагами достройки."""
    text = pg.SCHEMA_PATH.read_text(encoding="utf-8")
    return [match.group(1) for match in CREATE_TABLE.finditer(text)]


def test_schema_of_postgres_names_every_table_of_the_store():
    """Ни одна таблица не потерялась при переводе: тело, секция `steps` и вьюхи идут все."""
    translated = pg.schema()
    named = {match.group(1) for match in CREATE_TABLE.finditer(translated)}
    assert named == set(_sqlite_tables()), f"разъехались таблицы: {named ^ set(_sqlite_tables())}"
    views = {match.group(1) for match in re.finditer(r"create view (\w+)", translated, re.I)}
    assert views == {"v_singles_pool", "v_rating_pool"}


def test_schema_keeps_columns_and_keys_in_the_same_order():
    """Колонки переводятся без перестановок: по ним сверяются снимки строк журнала."""
    source = pg.SCHEMA_PATH.read_text(encoding="utf-8")
    translated = pg.schema()
    for table in ("matches", "side_players", "player_aliases", "corrections", "tournament_docs"):
        assert _columns(_table(translated, table)) == _columns(_table(source, table)), table


def test_identity_columns_stay_writable_because_the_journal_sets_ids():
    """`GENERATED BY DEFAULT`, а не `ALWAYS`: откат вставляет строку с её прежним id явно."""
    translated = _instructions(pg.schema())
    assert "GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in translated
    assert "GENERATED ALWAYS" not in translated
    plain = re.findall(r"\bid\s+INTEGER PRIMARY KEY\b", translated, re.IGNORECASE)
    assert not plain, f"остались колонки без идентичности: {plain}"


def test_timestamp_defaults_keep_the_text_shape():
    """Часы по умолчанию — текст в том же формате, что печатает `_now()`: по ним живёт очередь."""
    source = _instructions(pg.SCHEMA_PATH.read_text(encoding="utf-8"))
    translated = _instructions(pg.schema())
    assert "datetime('now')" not in translated
    assert translated.count(pg.NOW_TEXT) == source.count("datetime('now')"), "дефолт потерян"
    assert "timestamptz" not in translated  # колонки остаются TEXT, как в SQLite-файле


def test_sqlite_only_syntax_does_not_survive_the_translation():
    """Ни `PRAGMA`, ни JSON-функции SQLite в PG-инструкциях не остаётся."""
    translated = _instructions(pg.schema())
    for leftover in ("PRAGMA", "json_extract", "json_group_array", "json_object(", "fold("):
        assert leftover not in translated, leftover


def test_views_come_over_with_their_json_and_filters():
    """Вьюхи рейтингового пула переводятся целиком: на них держатся читатели и проверка года."""
    translated = _instructions(pg.schema()).lower()
    assert "create view v_singles_pool" in translated
    assert "create view v_rating_pool" in translated
    assert "(d.payload)::json ->> 'season_year'" in translated
    assert translated.count("in_rating_pool = 1") == 1


def test_parameters_keep_their_numbers_and_can_repeat():
    """`?8` в фильтре поиска встречается дважды: именованный стиль это переживает, `%s` — нет."""
    values = ("сезон", "турнир", "тур", "ник", 0, "%с%", "%т%", "%1/2%", "%ник%")
    sql, named = pg.bind("select ?1, ?8, ?8, fold(x) from t where y = ?2", values)
    assert sql == "select %(p1)s, %(p8)s, %(p8)s, lower(x) from t where y = %(p2)s"
    assert named == {f"p{number}": value for number, value in enumerate(values, start=1)}


def test_plain_question_marks_are_numbered_in_order():
    """Запросы ядра пишутся на `?` без номеров — и они тоже должны получать имена по порядку."""
    sql, named = pg.bind("update matches set a = ?, b = ? where id = ?", (1, 2, 3))
    assert sql == "update matches set a = %(p1)s, b = %(p2)s where id = %(p3)s"
    assert named == {"p1": 1, "p2": 2, "p3": 3}


def test_question_mark_inside_a_text_is_not_a_parameter():
    """Вопросительный знак в подписи источника — не параметр: иначе запрос разъедется молча."""
    sql, named = pg.bind("select note from matches where note = 'что за ? игра' and id = ?", (7,))
    assert sql.count("%(") == 1 and "'что за ? игра'" in sql
    assert named == {"p1": 7}


def test_missing_parameter_is_named_instead_of_crashing_later():
    with pytest.raises(ValueError, match="не переданы"):
        pg.bind("select ?3", ("только один",))


def test_search_queries_bind_with_the_parameters_the_code_builds():
    """Главная связка: генератор сверяется с настоящими константами и настоящим списком параметров.

    `api.search()` собирает девять значений плюс лимит; если порядок или нумерация разъедутся,
    psycopg возьмёт не те фильтры и человек получит чужие строки вместо пустого ответа.
    """
    asked = ("season 7", "", "1/2", "")
    params = (*asked, 1, *(f"%{value}%" for value in asked), 60)
    translated, named = pg.bind(api.SEARCH_SQL, params)
    assert "?" not in translated
    assert named["p10"] == 60 and named["p6"] == "%season 7%"
    used = {int(number) for number in re.findall(r"%\(p(\d+)\)s", translated)}
    assert used <= set(range(1, len(params) + 1)), f"запрос зовёт параметры {sorted(used)}"
    # Счётчик того же среза обязан использовать те же номера, кроме лимита.
    counted, _ = pg.bind(api.SEARCH_COUNT_SQL, params[:-1])
    assert {int(n) for n in re.findall(r"%\(p(\d+)\)s", counted)} == used - {10}


def _sql_of(module):
    """Все SQL-константы модуля: охрана должна ловить и ту, что появится завтра."""
    return {name: value for name, value in vars(module).items()
            if "SQL" in name and isinstance(value, str) and value.strip()}


def test_edit_path_carries_no_dialect_the_generator_does_not_know():
    """Охрана от следующего правщика: любой SQLite-изм в запросах пути правки должен быть известен.

    Проверяется остатком: после перевода в инструкции не должно остаться ни JSON-функций SQLite,
    ни `fold`, ни `group_concat`, ни часов `datetime('now')`. Список констант берётся из модулей,
    поэтому новая фраза в новом запросе упрётся именно сюда.
    """
    seen = 0
    for module in (api, edit, publish):
        for name, statement in sorted(_sql_of(module).items()):
            seen += 1
            translated = _instructions(pg.translate(statement))
            leftover = [token for token in ("fold(", "group_concat", "json_extract",
                                            "json_group_array", "json_object(", "datetime('now')",
                                            "PRAGMA")
                        if token in translated]
            assert not leftover, f"{module.__name__}.{name}: перевод не снял {leftover}"
    assert seen > 15, f"констант найдено всего {seen} — похоже, поиск сломался"


def test_store_connection_registers_the_folding_function():
    """`fold()` живёт на соединении: без него запросы поиска слепнут на кириллице."""
    con = store.connect()
    try:
        assert con.execute("select fold(' Дворовая   Лига ')").fetchone()[0] == "дворовая лига"
        assert con.execute("select fold(null)").fetchone()[0] == ""
    finally:
        con.close()
