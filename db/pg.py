"""Postgres-вариант той же схемы и тех же запросов: текст на входе, текст на выходе.

Перенос записи на серверную базу упирается не в драйвер, а в диалект. Приёмов SQLite, на которых
держится путь правки, осталось четыре: `fold()`, `json_extract()`,
`json_group_array()`/`json_object()`, `datetime('now')` вместе с `PRAGMA` и номера параметров `?3`.
Состав стороны и отпечаток базы собирает Python — `group_concat` без обещанного порядка на них не
работает, а с `order by` требует SQLite не старше 3.44, которого в рантайме публикации никто не
обещал.

Схема собирается из единого источника — `db/schema.sql` — поэтому правка таблицы не требует
второго файла, за которым надо угонять.

Живой проверки здесь не было и быть не может: Postgres в этом окружении отсутствует целиком, ни
сервера, ни клиента. Модуль потому без побочных эффектов: вход — текст, выход — текст, и всё это
сверяется строками в `tests/test_pg.py`. Расхождения, которые тут останутся непроверенными,
вскроются на парных тестах двух движков, когда база появится.
"""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCHEMA_PATH = ROOT / "db" / "schema.sql"
STEP_MARKER = "-- === steps ==="
VIEW_MARKER = "-- === views ==="

# SQLite считает `datetime('now')` текстом в UTC, и колонки схемы — TEXT. В Postgres `now()` —
# timestamptz, и приводить его к тексту надо в том же формате: иначе часы в базе перестанут
# сравниваться с `_now()` из db/edit.py, а по ним живёт очередь публикаций.
NOW_TEXT = "to_char(now() at time zone 'utc', 'YYYY-MM-DD HH24:MI:SS')"


def translate(statement):
    """Один оператор SQLite → он же на Postgres.

    Правила сняты с конкретных мест проекта: каждое из них что-то ломает, если его не применить.
    Комментарии сохраняются — в сгенерированном DDL они объясняют не меньше, чем в исходном файле.
    """
    # `PRAGMA` — настройка соединения, а не часть схемы: она живёт в db/store.py. Снимаем только
    # её строку, пояснение над ней остаётся.
    sql = re.sub(r"^\s*PRAGMA[^;]*;?\s*$", "", statement,
                 flags=re.IGNORECASE | re.MULTILINE).strip()
    if not re.search(r"\w", re.sub(r"^--.*$", "", sql, flags=re.MULTILINE)):
        return ""  # от блока комментариев без инструкции ничего не остаётся
    sql = re.sub(r"\bINTEGER\s+PRIMARY\s+KEY\b",
                 "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", sql, flags=re.IGNORECASE)
    # `db/build_db.py` считает «duplicate column name» нормой достройки; в Postgres та же норма
    # существует как синтаксис, иначе второй прогон схемы падал бы.
    sql = re.sub(r"\badd column\b", "add column if not exists", sql, flags=re.IGNORECASE)
    sql = re.sub(r"\bdrop column\b(?! if)", "drop column if exists", sql, flags=re.IGNORECASE)
    sql = re.sub(r"\(datetime\('now'\)\)", f"({NOW_TEXT})", sql, flags=re.IGNORECASE)
    sql = re.sub(r"\bjson_extract\(\s*([\w.]+)\s*,\s*'\$\.(\w+)'\s*\)",
                 r"(\1)::json ->> '\2'", sql, flags=re.IGNORECASE)
    sql = re.sub(r"\bjson_object\b", "json_build_object", sql, flags=re.IGNORECASE)
    sql = re.sub(r"\bjson_group_array\b", "json_agg", sql, flags=re.IGNORECASE)
    return re.sub(r"\bfold\(", "lower(", sql, flags=re.IGNORECASE)


def schema():
    """DDL для Postgres: тело схемы, шаги достройки и вьюхи — в том же порядке, что в файле."""
    text = SCHEMA_PATH.read_text(encoding="utf-8")
    body, rest = text.split(STEP_MARKER, 1)
    steps, views = rest.split(VIEW_MARKER, 1)
    kept = []
    for part in re.split(r";\s*\n", body + "\n" + steps + "\n" + views):
        statement = translate(part)
        if statement:
            kept.append(statement + ";")
    if not kept:
        raise RuntimeError(f"из {SCHEMA_PATH} не собралось ни одной инструкции")
    return "\n\n".join(kept) + "\n"


def bind(statement, params):
    """Запрос с `?` и `?3` → тот же запрос с именованными параметрами для psycopg.

    Номера важны: `?8` в фильтре поиска встречается дважды, и positional-стиль `%s` заставил бы
    дублировать значения в списке. Имена `p1, p2, …` соответствуют номерам SQLite, так что
    рассинхрон при ошибке видно глазами. Вопрос внутри строкового литерала параметром не считается.
    """
    named = {f"p{key}": value for key, value in enumerate(params, start=1)}
    state = {"position": 0}

    def _replace(match):
        digits = match.group(1)
        if digits:
            state["position"] = max(state["position"], int(digits))
            return f"%(p{digits})s"
        state["position"] += 1
        return f"%(p{state['position']})s"

    parts = re.split(r"('(?:[^']|'')*')", statement)
    sql = "".join(part if part.startswith("'") else re.sub(r"\?(\d*)", _replace, part)
                  for part in parts)
    missing = sorted({f"p{number}" for number in re.findall(r"%\(p(\d+)\)s", sql)
                      if f"p{number}" not in named})
    if missing:
        raise ValueError(f"параметры {missing} названы в запросе, но не переданы")
    return translate(sql), named
